"""API Router for multi-agent experimentation platform workflows."""
from __future__ import annotations

from fastapi import APIRouter, HTTPException, Query

from credit_risk_model.agents.orchestrator import Orchestrator
from credit_risk_model.agents.planner_agent import PlannerAgent
from credit_risk_model.experimentation.schemas import (
    CandidatePromotionRequest,
    CandidatePromotionResponse,
    ExperimentObjective,
    WorkflowResult,
)
from credit_risk_model.experimentation.store import ExperimentStore

router = APIRouter(prefix="/api/experiments", tags=["experiments"])


def _orchestrator() -> Orchestrator:
    return Orchestrator()


@router.post("", response_model=WorkflowResult)
def create_experiment_workflow(objective: ExperimentObjective):
    """Start a bounded multi-agent experimentation workflow planned by Planner Agent and executed by Orchestrator."""
    planner = PlannerAgent()
    orchestrator = _orchestrator()
    try:
        plan = planner.generate_plan(objective)
        return orchestrator.run_workflow(objective, plan=plan)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Experimentation workflow failed: {exc}") from exc


@router.get("", response_model=list[WorkflowResult])
def list_experiment_workflows(limit: int = Query(20, ge=1, le=100)):
    """List recent experiment workflows."""
    store = ExperimentStore()
    return store.list_workflows(limit=limit)


@router.get("/{workflow_id}", response_model=WorkflowResult)
def get_experiment_workflow(workflow_id: str):
    """Retrieve detailed state of a specific experimentation workflow."""
    store = ExperimentStore()
    workflow = store.get_workflow(workflow_id)
    if not workflow:
        raise HTTPException(status_code=404, detail=f"Workflow '{workflow_id}' not found")
    return workflow


@router.get("/{workflow_id}/plan")
def get_workflow_plan(workflow_id: str):
    """Retrieve the experiment plan markdown generated by the Planner Agent."""
    store = ExperimentStore()
    plan_path = store.get_plan_path(workflow_id)
    if not plan_path.exists():
        raise HTTPException(status_code=404, detail=f"Experiment plan for '{workflow_id}' not found")
    return {
        "workflow_id": workflow_id,
        "plan_markdown": plan_path.read_text(encoding="utf-8"),
        "plan_path": str(plan_path),
    }


@router.get("/{workflow_id}/results")
def get_workflow_results(workflow_id: str):
    """Retrieve structured comparison of baseline vs candidate models for a workflow."""
    store = ExperimentStore()
    workflow = store.get_workflow(workflow_id)
    if not workflow:
        raise HTTPException(status_code=404, detail=f"Workflow '{workflow_id}' not found")

    comparison = []
    for exp in workflow.experiments:
        comparison.append({
            "experiment_id": exp.experiment_id,
            "iteration": exp.iteration,
            "model_type": exp.model_type,
            "status": exp.status.value,
            "metrics": exp.metrics,
            "passed_criteria": exp.passed_criteria,
            "duration_seconds": exp.duration_seconds,
            "feedback": exp.criteria_feedback,
        })

    return {
        "workflow_id": workflow.workflow_id,
        "status": workflow.status.value,
        "selected_candidate_id": workflow.selected_candidate_id,
        "candidate_reasoning": workflow.candidate_reasoning,
        "promotion_status": workflow.promotion_status,
        "baseline_metrics": workflow.baseline_metrics,
        "experiments": comparison,
    }


@router.post("/{workflow_id}/approve", response_model=CandidatePromotionResponse)
def approve_candidate(workflow_id: str, request: CandidatePromotionRequest, experiment_id: str | None = None):
    """Promote an eligible candidate model from a workflow to the governance model inventory."""
    orchestrator = _orchestrator()
    workflow = ExperimentStore().get_workflow(workflow_id)
    if not workflow:
        raise HTTPException(status_code=404, detail=f"Workflow '{workflow_id}' not found")

    target_exp_id = experiment_id or workflow.selected_candidate_id
    if not target_exp_id:
        raise HTTPException(status_code=400, detail="No candidate model selected or specified for promotion")

    try:
        return orchestrator.promote_candidate(workflow_id, target_exp_id, request)
    except (ValueError, LookupError) as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to promote candidate: {exc}") from exc
